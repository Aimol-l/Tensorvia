#!/usr/bin/env python3
"""Compile Tensorvia's GLSL compute shaders and emit the SPIR-V registry.

Input:  shader/**/*.comp  (one shader per operator/dtype pair)
Output: <out>/spirv/spv_registry.h
        <out>/spirv/spv_registry.cpp

The registry key is the shader file stem (``relu_float32``), which is exactly
what VulkanContext::registerOp builds with make_pipeline_key(). Missing keys
therefore fail at runtime with "SPIR-V not found"; this script fails the build
instead.

Determinism matters: the output is sorted by key and written atomically, so a
rebuild over the same shader set produces byte-identical files and mcpp does
not recompile the world on every invocation.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import os
import subprocess
import sys
import tempfile
from pathlib import Path


def find_shaders(shader_root: Path) -> list[Path]:
    return sorted(shader_root.glob("*/*.comp"))


def compile_one(shader: Path, spv_dir: Path, glslang: str) -> Path:
    out_path = spv_dir / (shader.stem + ".spv")
    cmd = [
        glslang,
        "-V",
        "--target-env",
        "vulkan1.4",
        str(shader),
        "-o",
        str(out_path),
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(
            f"gen_spv: failed to compile {shader}\n{proc.stdout}{proc.stderr}"
        )
        raise SystemExit(1)
    if not out_path.is_file() or out_path.stat().st_size == 0:
        sys.stderr.write(f"gen_spv: {shader} produced no SPIR-V\n")
        raise SystemExit(1)
    return out_path


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def emit_registry(spv_files: list[Path], out_dir: Path) -> None:
    """Write the header and the registry translation unit."""
    entries = []
    for spv in sorted(spv_files, key=lambda p: p.stem):
        data = spv.read_bytes()
        if len(data) % 4 != 0:
            raise SystemExit(f"gen_spv: {spv} size {len(data)} is not a multiple of 4")
        words = [
            int.from_bytes(data[i : i + 4], "little")
            for i in range(0, len(data), 4)
        ]
        entries.append((spv.stem, words))

    cpp = [
        "// Generated by tools/gen_spv.py for the CMake lane -- do not edit.",
        "//",
        "// The mcpp lane does not use this script: build.mcpp generates the same",
        "// table from mcpp.rules.spirv's surface, which is what removes both Python",
        "// and a host shader compiler from that build. The interface is shared --",
        "// include/tensorvia/backend/vulkan/spv_registry.hpp -- so a source file",
        "// cannot tell which lane produced the bytes.",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <stdexcept>",
        "#include <string>",
        "#include <string_view>",
        "#include <unordered_map>",
        "",
        '#include "tensorvia/backend/vulkan/spv_registry.hpp"',
        "",
        "namespace vkspv {",
        "namespace {",
        "",
    ]
    for key, words in entries:
        # 12 words per line keeps the generated file readable without making
        # the compiler work through one enormous line.
        cpp.append(f"const std::uint32_t {key}_data[] = {{")
        for i in range(0, len(words), 12):
            chunk = ", ".join(f"0x{w:08x}u" for w in words[i : i + 12])
            cpp.append(f"    {chunk},")
        cpp.append("};")
        cpp.append("")

    cpp.append("struct entry {")
    cpp.append("    const std::uint32_t* code;")
    cpp.append("    std::size_t          words;")
    cpp.append("};")
    cpp.append("")
    cpp.append("const std::unordered_map<std::string_view, entry>& table() {")
    cpp.append("    static const std::unordered_map<std::string_view, entry> t = {")
    for key, words in entries:
        cpp.append(f'        {{"{key}", {{{key}_data, {len(words)}}}}},')
    cpp.append("    };")
    cpp.append("    return t;")
    cpp.append("}")
    cpp.append("")
    cpp.append("}  // namespace")
    cpp.append("")
    cpp.append("spv_view get_spv_code(std::string_view key) {")
    cpp.append("    const auto& t  = table();")
    cpp.append("    const auto  it = t.find(key);")
    cpp.append("    if (it == t.end()) {")
    cpp.append('        throw std::runtime_error("SPIR-V not found: " + std::string(key));')
    cpp.append("    }")
    cpp.append("    return {it->second.code, it->second.words};")
    cpp.append("}")
    cpp.append("")
    cpp.append("}  // namespace vkspv")
    cpp.append("")

    # Only the translation unit: the declarations are hand-written and shared
    # with the mcpp lane, so there is no generated header to keep in step.
    atomic_write(out_dir / "spirv" / "spv_registry.cpp", "\n".join(cpp))


def main() -> int:
    here = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True, type=Path, help="output root (writes <out>/spirv)")
    ap.add_argument("--shader-root", type=Path, default=here / "shader")
    ap.add_argument("--glslang", default="glslangValidator")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 1)
    args = ap.parse_args()

    shaders = find_shaders(args.shader_root)
    if not shaders:
        sys.stderr.write(f"gen_spv: no .comp shaders under {args.shader_root}\n")
        return 1

    args.out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="tv-spv-", dir=args.out) as tmp:
        spv_dir = Path(tmp)
        with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, args.jobs)) as pool:
            futures = [
                pool.submit(compile_one, shader, spv_dir, args.glslang)
                for shader in shaders
            ]
            try:
                for future in concurrent.futures.as_completed(futures):
                    future.result()
            except FileNotFoundError:
                sys.stderr.write(
                    f"gen_spv: glslang compiler not found: {args.glslang}\n"
                    "         install glslang, add it to PATH, or pass --glslang <path>\n"
                )
                return 1
        emit_registry(list(spv_dir.glob("*.spv")), args.out)

    print(f"gen_spv: {len(shaders)} shaders -> {args.out / 'spirv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
