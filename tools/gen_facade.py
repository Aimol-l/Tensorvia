#!/usr/bin/env python3
"""Generate or verify the mcpp module wrapper's export block.

mcpp 路径的薄包装 `src/interface/tensorvia.ixx`：全局模块片段 include 头文件
事实源（interface/tensorvia.hpp），export 出公开 API 面。这个文件是机械的：

    module;
    #include "interface/tensorvia.hpp"
    export module tensorvia;
    export using ::Tensor;
    export namespace ops { using ::ops::Add; ... }

从 `tools/facade_exports.def` 生成它意味着新的公开名字不会被忘记：
`--check` 抓漂移，tests/facade_api.cpp 让编译器抓住从未列进清单的名字。

Usage:
    python3 tools/gen_facade.py --write   # regenerate tensorvia.ixx
    python3 tools/gen_facade.py --check   # fail if it is out of date
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_DEF = ROOT / "tools" / "facade_exports.def"
DEFAULT_OUT = ROOT / "src" / "interface" / "tensorvia.ixx"
DEFAULT_TEST_OUT = ROOT / "tests" / "facade_api.cpp"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
HEADER = (
    "// 由 tools/gen_facade.py 从 tools/facade_exports.def 生成，请勿手改。\n"
    "//\n"
    "// mcpp 路径的模块包装：全局模块片段 include 头文件事实源，export 出公开\n"
    "// API 面。没有任何逻辑代码；清单与头文件的一致性由 --check 守卫，名字\n"
    "// 的存在性由 tests/facade_api.cpp 编译守卫。\n"
)
TEST_HEADER = (
    "// Generated by tools/gen_facade.py from tools/facade_exports.def. Do not edit.\n"
    "//\n"
    "// Compile-time surface check: block-scope using-declarations only test that\n"
    "// the name is visible through `import tensorvia;`, so a name missing from the\n"
    "// facade fails the build instead of silently shrinking the public API.\n"
)


def parse(path: pathlib.Path) -> dict[str, list[str]]:
    sections: dict[str, list[str]] = {}
    current: str | None = None
    for lineno, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            current = line[1:-1].strip()
            if current in sections:
                raise SystemExit(f"{path}:{lineno}: duplicate section [{current}]")
            sections[current] = []
            continue
        if current is None:
            raise SystemExit(f"{path}:{lineno}: name outside a section: {line}")
        if not IDENT.match(line):
            raise SystemExit(f"{path}:{lineno}: not a C++ identifier: {line}")
        sections[current].append(line)
    for required in ("global", "tensorvia", "ops"):
        sections.setdefault(required, [])
    return sections


def render(sections: dict[str, list[str]]) -> str:
    out = [HEADER, "module;\n", '#include "interface/tensorvia.hpp"\n\n',
           "export module tensorvia;\n\n"]
    if sections["global"]:
        for name in sections["global"]:
            out.append(f"export using ::{name};\n")
        out.append("\n")
    if sections["tensorvia"]:
        out.append("export namespace tensorvia {\n")
        for name in sections["tensorvia"]:
            out.append(f"using ::tensorvia::{name};\n")
        out.append("}\n\n")
    if sections["ops"]:
        out.append("export namespace ops {\n")
        for name in sections["ops"]:
            out.append(f"using ::ops::{name};\n")
        out.append("}\n")
    return "".join(out)


def render_test(sections: dict[str, list[str]]) -> str:
    out = [TEST_HEADER, "#include <gtest/gtest.h>\n\n", "import tensorvia;\n\n",
           "TEST(Facade, PublicNamesAreExported) {\n"]
    for name in sections["global"]:
        out.append(f"    using ::{name};\n")
    for name in sections["tensorvia"]:
        out.append(f"    using ::tensorvia::{name};\n")
    for name in sections["ops"]:
        out.append(f"    using ::ops::{name};\n")
    out.append("    SUCCEED();\n}\n")
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the facade")
    group.add_argument("--check", action="store_true", help="verify it is current")
    parser.add_argument("--def-file", type=pathlib.Path, default=DEFAULT_DEF)
    parser.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    parser.add_argument("--test-out", type=pathlib.Path, default=DEFAULT_TEST_OUT)
    args = parser.parse_args()

    sections = parse(args.def_file)
    expected = {args.out: render(sections), args.test_out: render_test(sections)}

    if args.write:
        for path, text in expected.items():
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
        return 0

    failed = False
    for path, text in expected.items():
        try:
            actual = path.read_text(encoding="utf-8")
        except FileNotFoundError:
            print(f"{path} is missing; run tools/gen_facade.py --write", file=sys.stderr)
            failed = True
            continue
        if actual != text:
            print(f"{path} is out of date; run tools/gen_facade.py --write", file=sys.stderr)
            failed = True
    if not failed:
        print("facade and surface test are up to date")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
